function fixFile(filePath) {
  try {
    let content = fs.readFileSync(filePath, 'utf8');
    let original = content;
    let changed = false;
    
    for (const fix of fixes) {
      if (content.includes(fix.from)) {
        content = content.split(fix.from).join(fix.to);
        changed = true;
      }
    }
    
    // Also fix standalone replacement chars that might remain
    if (content.includes('\uFFFD')) {
      content = content.replace(/\uFFFD/g, '');
      changed = true;
    }
    
    if (changed) {
      fs.writeFileSync(filePath, content, 'utf8');
      console.log('Fixed:', filePath);
    }
  } catch (e) {
    console.error('Error fixing', filePath, e.message);
  }
}

function walk(dir) {
  const files = fs.readdirSync(dir);
  for (const f of files) {
    const fp = path.join(dir, f);
    const stat = fs.statSync(fp);
    if (stat.isDirectory() && !['node_modules','.git','dist','build','.next','coverage','.kilo','playwright-report'].includes(f)) {
      walk(fp);
    } else if (stat.isFile() && /\.(js|html|css|json|md|sql|txt)$/.test(f)) {
      fixFile(fp);
    }
  }
}

